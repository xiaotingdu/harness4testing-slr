"""Generate the appendix table of the 154 proposed systems by task and ETCLOVG components.

Inputs: tools/corpus_154.csv (titles and citation keys) and
tools/proposed_system_components_154.csv (task and component signature).
Output: tables/task_feature_tables.tex.
Run from the repository root: python tools/build_appendix_table.py
"""
from __future__ import annotations

import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CORPUS = ROOT / "tools" / "corpus_154.csv"
SYSTEMS = ROOT / "tools" / "proposed_system_components_154.csv"
OUT = ROOT / "tables" / "task_feature_tables.tex"

TASKS = [
    ("unit_test_generation", "Unit-test generation"),
    ("test_oracle_generation", "Test-oracle generation"),
    ("system_test_input_generation", "System-test-input generation"),
    ("bug_analysis", "Bug analysis"),
    ("debugging", "Debugging"),
    ("program_repair", "Program repair"),
]
ESCAPES = {"&": r"\&", "%": r"\%", "_": r"\_", "#": r"\#", "$": r"\$"}


def read(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle))


def escape(text: str) -> str:
    return "".join(ESCAPES.get(ch, ch) for ch in " ".join(text.split()))


corpus = {row["record_id"]: row for row in read(CORPUS)}
systems = read(SYSTEMS)
if len(systems) != 154 or set(corpus) != {row["record_id"] for row in systems}:
    raise ValueError("Corpus and system files do not describe the same 154 papers")

header = r"""% Generated by tools/build_appendix_table.py; do not edit directly.
% Sources: tools/corpus_154.csv and tools/proposed_system_components_154.csv.

\begingroup
\footnotesize
\setlength{\tabcolsep}{2pt}
\renewcommand{\arraystretch}{1.10}
\begin{longtable}{@{}>{\raggedright\arraybackslash}p{0.50\linewidth} >{\raggedright\arraybackslash}p{0.24\linewidth} >{\raggedright\arraybackslash}p{0.18\linewidth}@{}}
\caption{Papers proposing testing systems by primary software-testing task and ETCLOVG components ($N=154$).}\label{tab:included-study-components}\\
\toprule
Paper title & Testing task & Harness components \\
\midrule
\endfirsthead
\multicolumn{3}{l}{\tablename\ \thetable\ (continued)}\\
\toprule
Paper title & Testing task & Harness components \\
\midrule
\endhead
\midrule
\multicolumn{3}{r}{Continued on next page}\\
\endfoot
\bottomrule
\endlastfoot
"""
lines = [header.rstrip("\n")]
for task, label in TASKS:
    rows = sorted((r for r in systems if r["task"] == task),
                  key=lambda r: corpus[r["record_id"]]["title"].casefold())
    for row in rows:
        paper = corpus[row["record_id"]]
        lines.append(f"{{{escape(paper['title'])}}}~\\cite{{{paper['bib_key']}}} & {label} & "
                     f"\\texttt{{{row['engineering_components']}}} \\\\")
lines += [r"\end{longtable}", r"\endgroup", ""]
OUT.write_text("\n".join(lines), encoding="utf-8")
print("written", OUT.name, "with", len(systems), "rows")
